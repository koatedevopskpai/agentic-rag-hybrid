"""Eval gate: assertion-based retrieval checks (relevancy + groundedness).

Usage: python evals/evaluate.py
Exit 0 on pass, 1 on any failure. Writes evals/EVAL_REPORT.md.
"""

from __future__ import annotations

import json
import pathlib
import sys

from agentic_rag_hybrid import Corpus, retrieve, tokenize

REPO = pathlib.Path(__file__).resolve().parents[1]
EVALS = pathlib.Path(__file__).parent / "golden_queries.json"
REPORT = pathlib.Path(__file__).parent / "EVAL_REPORT.md"


def main() -> int:
    data = json.loads(EVALS.read_text(encoding="utf-8"))
    corpus = Corpus(data["corpus"])
    failures: list[str] = []
    rows: list[str] = []

    for case in data["queries"]:
        top = [doc for doc, _ in retrieve(corpus, case["query"], top_k=case["top_k"])]
        expected = case["expected_in_top"]
        missing = [d for d in expected if d not in top]
        grounded = all(
            set(tokenize(corpus[doc])) & set(tokenize(case["query"])) for doc in top
        )
        ok = not missing and grounded
        rows.append(
            f"| {case['query']} | {','.join(top)} | {','.join(expected)} | "
            f"{'PASS' if ok else 'FAIL'} |"
        )
        if missing:
            failures.append(f"{case['query']}: expected {missing} in top {case['top_k']}")
        if not grounded:
            failures.append(f"{case['query']}: groundedness failed for {top}")

    lines = [
        "# Evaluation report",
        "",
        f"_Generated by `python evals/evaluate.py` — deterministic hybrid (BM25 + signature) + RRF + groundedness. {len(rows)} case(s)._",
        "",
        "| Query | Top results | Expected in top | Result |",
        "|---|---|---|---|",
        *rows,
        "",
        *([] if failures else ["**All golden cases pass.**"]),
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if failures:
        print("EVAL FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"ALL golden cases pass ({len(rows)} cases). Report written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())