"""Eval gate: assertion-based retrieval checks (relevancy + groundedness).

Usage: python evals/evaluate.py
Exit 0 on pass, 1 on any failure. Writes evals/EVAL_REPORT.md.
"""

from __future__ import annotations

import json
import pathlib
import sys

from agentic_rag_hybrid import Corpus, GraphRAG, KnowledgeGraph, retrieve, tokenize

REPO = pathlib.Path(__file__).resolve().parents[1]
EVALS = pathlib.Path(__file__).parent / "golden_queries.json"
GRAPH_EVALS = pathlib.Path(__file__).parent / "golden_graph.json"
REPORT = pathlib.Path(__file__).parent / "EVAL_REPORT.md"


def run_text_cases() -> tuple[list[str], list[str]]:
    data = json.loads(EVALS.read_text(encoding="utf-8"))
    corpus = Corpus(data["corpus"])
    failures: list[str] = []
    rows: list[str] = []

    for case in data["queries"]:
        top = [doc for doc, _ in retrieve(corpus, case["query"], top_k=case["top_k"])]
        expected = case["expected_in_top"]
        missing = [d for d in expected if d not in top]
        grounded = all(
            set(tokenize(corpus[doc])) & set(tokenize(case["query"])) for doc in top
        )
        ok = not missing and grounded
        rows.append(
            f"| {case['query']} | {','.join(top)} | {','.join(expected)} | "
            f"{'PASS' if ok else 'FAIL'} |"
        )
        if missing:
            failures.append(f"{case['query']}: expected {missing} in top {case['top_k']}")
        if not grounded:
            failures.append(f"{case['query']}: groundedness failed for {top}")
    return rows, failures


def run_graph_cases() -> tuple[list[str], list[str]]:
    data = json.loads(GRAPH_EVALS.read_text(encoding="utf-8"))
    graph = KnowledgeGraph()
    for ent in data["entities"]:
        graph.add_entity(ent["id"], type=ent.get("type", "node"), aliases=tuple(ent.get("aliases", [])))
    for src, rel, dst in data["relations"]:
        graph.add_relation(src, rel, dst)
    engine = GraphRAG(graph)

    failures: list[str] = []
    rows: list[str] = []
    for case in data["queries"]:
        top = [node for node, _text, _score in engine.retrieve(case["query"], top_k=case["top_k"])]
        expected = case["expected_in_top"]
        missing = [n for n in expected if n not in top]
        ok = not missing and bool(top)
        rows.append(
            f"| {case['query']} | {','.join(top)} | {','.join(expected)} | "
            f"{'PASS' if ok else 'FAIL'} |"
        )
        if not ok:
            failures.append(f"{case['query']}: got {top}, expected {expected} in top")
    return rows, failures


def main() -> int:
    text_rows, text_failures = run_text_cases()
    graph_rows, graph_failures = run_graph_cases()
    failures = text_failures + graph_failures

    lines = [
        "# Evaluation report",
        "",
        f"_Generated by `python evals/evaluate.py` — deterministic hybrid (BM25 + signature) + RRF + groundedness, plus GraphRAG expansion. {len(text_rows) + len(graph_rows)} case(s)._",
        "",
        "## Text retrieval",
        "",
        "| Query | Top results | Expected in top | Result |",
        "|---|---|---|---|",
        *text_rows,
        "",
        "## Graph retrieval (entity expansion)",
        "",
        "| Query | Top nodes | Expected in top | Result |",
        "|---|---|---|---|",
        *graph_rows,
        "",
        *([] if failures else ["**All golden cases pass.**"]),
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if failures:
        print("EVAL FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"ALL golden cases pass ({len(text_rows) + len(graph_rows)} cases). Report written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())